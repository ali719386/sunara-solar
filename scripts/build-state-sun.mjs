// Builds lib/stateSun.ts: the month by month peak sun hours for the largest city of every US
// state, so the calculator's Sun intensity card shows instantly with no request at runtime.
//
// Run once (and again only if you want fresher data): node scripts/build-state-sun.mjs
// Needs NLR_API_KEY in .env.local (free: https://developer.nlr.gov/signup/).
// 1. OpenStreetMap Nominatim finds each city (one request a second, as its policy asks).
// 2. NLR (formerly NREL) PVWatts v8 returns its solar resource from NSRDB satellite data.

import { readFileSync, writeFileSync } from "node:fs";

const env = Object.fromEntries(
  readFileSync(".env.local", "utf8")
    .split(/\r?\n/)
    .filter((l) => /^[A-Z_]+=/.test(l))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()])
);
const KEY = env.NLR_API_KEY || "DEMO_KEY";

// Read the state list and largest cities straight from lib/usStates.ts so they never drift.
const src = readFileSync("lib/usStates.ts", "utf8");
const states = [...src.matchAll(/\{ name: "([^"]+)", code: "([A-Z]{2})"/g)].map((m) => ({ name: m[1], code: m[2] }));
const cityBlock = src.slice(src.indexOf("export const LARGEST_CITY"));
const cities = Object.fromEntries([...cityBlock.matchAll(/([A-Z]{2}): "([^"]+)"/g)].map((m) => [m[1], m[2]]));
if (states.length !== 51) throw new Error(`expected 51 states, found ${states.length}`);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const round1 = (n) => Math.round(n * 10) / 10;

async function geocode(city, state) {
  const params = new URLSearchParams({ q: `${city}, ${state}`, countrycodes: "us", format: "jsonv2", limit: "1" });
  const res = await fetch(`https://nominatim.openstreetmap.org/search?${params}`, {
    headers: { "User-Agent": "SUNARA-solar-calculator/1.0 (+https://sunara-solar-tawny.vercel.app)" },
  });
  const [hit] = await res.json();
  if (!hit) throw new Error(`not found: ${city}, ${state}`);
  return { lat: Number(hit.lat), lon: Number(hit.lon) };
}

async function pvwatts(lat, lon) {
  const params = new URLSearchParams({
    api_key: KEY, lat: lat.toFixed(4), lon: lon.toFixed(4), system_capacity: "4", azimuth: "180", tilt: "20",
    array_type: "1", module_type: "0", losses: "14", dataset: "nsrdb",
  });
  const res = await fetch(`https://developer.nlr.gov/api/pvwatts/v8.json?${params}`);
  const j = await res.json();
  if (j.errors?.length || !j.outputs) throw new Error(`PVWatts ${res.status}: ${j.errors?.join("; ") ?? "no outputs"}`);
  return { annual: round1(j.outputs.solrad_annual), monthly: j.outputs.solrad_monthly.map(round1), source: j.station_info?.weather_data_source ?? "" };
}

const rows = [];
let source = "";
for (const s of states) {
  const city = cities[s.code];
  const { lat, lon } = await geocode(city, s.name);
  await sleep(1100);
  const pv = await pvwatts(lat, lon);
  source ||= pv.source;
  rows.push(`  ${s.code}: { city: ${JSON.stringify(city)}, annual: ${pv.annual}, monthly: [${pv.monthly.join(", ")}] },`);
  console.log(`${s.code} ${city}: ${pv.annual}`);
}

writeFileSync(
  "lib/stateSun.ts",
  `// Generated by scripts/build-state-sun.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Peak sun hours per day (kWh/m2/day) on a south facing roof at 20 degrees, for the largest city
// of each state. Source: NLR (formerly NREL) PVWatts v8, ${source || "NSRDB"}. Locations: OpenStreetMap.

export type StateSun = { city: string; annual: number; monthly: number[] };

export const stateSun: Record<string, StateSun> = {
${rows.join("\n")}
};
`
);
console.log(`wrote lib/stateSun.ts with ${rows.length} states`);
